const UNKNOWN = GLYPHS["?"];

function glyph(ch: string): readonly string[] {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? UNKNOWN;
}

export function textWidth(text: string, size = 1, spacing = 1): number {
  const n = [...text].length;
  if (n === 0) return 0;
  return n * (GLYPH_WIDTH * size + spacing) - spacing;
}

/** Draw `text` with its top-left at (x, y); `size` is the pixel block each glyph pixel becomes. */
export function drawText(canvas: Canvas, x: number, y: number, text: string, color: Color, size = 1, spacing = 1): number {
  let cursor = x;
  for (const ch of text) {
    const rows = glyph(ch);
    rows.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) if (row[i] === "#") canvas.fill(cursor + i * size, y + j * size, size, size, color);
    });
    cursor += GLYPH_WIDTH * size + spacing;
  }
  return cursor - spacing;
}
